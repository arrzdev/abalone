import { existsSync, readdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { describe, expect, it } from "vitest"
import { routes } from "@/routing/config"
import { SITEMAP } from "@/routing/seo-pages"

//the route table is data the router reads at build time. a file named here
//that is not on disk breaks the build for everyone, and a page on disk that no
//route names is a screen nobody can reach. neither needs a render to see.

const routingDir = dirname(fileURLToPath(import.meta.url))

type Node = {
  type: string
  file?: string
  path?: string
  children?: Node[]
}

type Entry = { url: string; file: string }

//the root's file is generated by the nativ plugin at build time
const GENERATED_ROOT = "layouts/__root.gen.tsx"

/** Every page and layout in the tree, with the url it answers at. */
function walk(node: Node, prefix: string): Entry[] {
  const own = node.path ? `${prefix}${node.path}` : prefix
  const entries: Entry[] = []
  if (node.file && node.type !== "root") {
    entries.push({ url: own || "/", file: node.file })
  }
  for (const child of node.children ?? []) {
    entries.push(...walk(child, own))
  }
  return entries
}

function pageFilesOnDisk(directory: string): string[] {
  const found: string[] = []
  for (const entry of readdirSync(join(routingDir, directory), {
    withFileTypes: true,
  })) {
    const path = `${directory}/${entry.name}`
    if (entry.isDirectory()) found.push(...pageFilesOnDisk(path))
    else if (entry.name.endsWith(".page.tsx")) found.push(path)
  }
  return found
}

const entries = walk(routes as unknown as Node, "")
const pages = entries.filter((entry) => entry.file.startsWith("pages/"))

describe("the route table", () => {
  it("only names files that exist", () => {
    for (const { file } of entries) {
      expect(existsSync(join(routingDir, file)), file).toBe(true)
    }
    expect(routes.file).toBe(GENERATED_ROOT)
  })

  it("answers each url with one page", () => {
    const urls = pages.map((page) => page.url)
    expect(urls.filter((url, i) => urls.indexOf(url) !== i)).toEqual([])
  })

  it("uses each page file once", () => {
    const files = pages.map((page) => page.file)
    expect(files.filter((file, i) => files.indexOf(file) !== i)).toEqual(
      [],
    )
  })

  it("leaves no page file unreachable", () => {
    const named = new Set(pages.map((page) => page.file))
    const onDisk = pageFilesOnDisk("pages")
    expect(onDisk.filter((file) => !named.has(file))).toEqual([])
  })

  it("keeps every url the app used to hand out", () => {
    const urls = pages.map((page) => page.url)
    for (const url of [
      "/login",
      "/games",
      "/game",
      "/game/offline",
      "/game/online",
      "/game/online/$gameId",
    ]) {
      expect(urls, url).toContain(url)
    }
  })

  it("has a route for every url in the sitemap", () => {
    const urls = new Set(pages.map((page) => page.url))
    for (const path of Object.keys(SITEMAP)) {
      expect(urls.has(path), path).toBe(true)
    }
  })
})
